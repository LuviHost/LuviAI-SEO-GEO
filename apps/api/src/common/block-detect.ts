/**
 * Tarayicimiz engellendi mi? — "sayfa yok/bozuk" ile "bize kapali" ayrimi.
 *
 * NEDEN VAR: ofsayt.com Cloudflare arkasinda RanksUp tarayicisina 403 "Sorry,
 * you have been blocked" donuyordu. Eski kod bunu "sayfa okunamadi" sayip
 * denetim skorunu dusurdu (44) — musteriye sitesi kotu gibi gosterildi, oysa
 * olculen sey sitenin kendisi degil, bizim erisimimizdi. Engeli tanidigimizda
 * puan VERMEYIZ; "erisim engellendi" der ve nasil izin verilecegini anlatiriz.
 *
 * Tespit yalnizca yaniti OKUR. Engeli asmaya calismayiz (tarayici taklidi,
 * challenge cozme vb. yok) — dogru yol site sahibinin izin vermesidir.
 */

export type BlockKind =
  /** Guvenlik duvari bizi acikca reddetti (Cloudflare "you have been blocked" vb.) */
  | 'waf'
  /** Bot dogrulamasi / JS challenge — icerik yerine dogrulama sayfasi geldi */
  | 'challenge'
  /** Giris gerekiyor (401/407) */
  | 'auth'
  /** Hiz siniri (429) */
  | 'rate_limited'
  /** Genel 403/451 — kaynagi belirsiz red */
  | 'forbidden'
  /** 503 — gecici hizmet disi */
  | 'unavailable';

export interface BlockSignal {
  kind: BlockKind;
  /** 'cloudflare' | 'akamai' | 'sucuri' | 'imperva' | 'aws' | 'datadome' | 'perimeterx' | 'vercel' | null */
  vendor: string | null;
  status: number;
  /** Kullaniciya gosterilecek kisa Turkce aciklama */
  reason: string;
}

export interface BlockProbe {
  status: number;
  /** Kucuk harf anahtarli basliklar (safeFetchText.headers bu bicimde) */
  headers: Record<string, string>;
  /** Govdenin ilk kismi yeterli (safeFetchText 2xx disinda 64 KB okur) */
  text?: string;
}

const VENDOR_NAME: Record<string, string> = {
  cloudflare: 'Cloudflare',
  akamai: 'Akamai',
  sucuri: 'Sucuri',
  imperva: 'Imperva',
  aws: 'AWS WAF / CloudFront',
  datadome: 'DataDome',
  perimeterx: 'HUMAN (PerimeterX)',
  vercel: 'Vercel',
};

function detectVendor(h: Record<string, string>, body: string): string | null {
  const server = (h['server'] ?? '').toLowerCase();
  if (server.includes('cloudflare') || h['cf-ray'] || h['cf-mitigated']) return 'cloudflare';
  if (h['x-sucuri-id'] || h['x-sucuri-block'] || /Sucuri WebSite Firewall/i.test(body)) return 'sucuri';
  if (h['x-iinfo'] || /imperva|incapsula/i.test(h['x-cdn'] ?? '') || /Incapsula incident ID|_Incapsula_Resource/i.test(body)) return 'imperva';
  if (h['x-datadome'] || h['x-dd-b'] || /captcha-delivery\.com/i.test(body)) return 'datadome';
  if (/px-captcha|_pxCaptcha|perimeterx/i.test(body)) return 'perimeterx';
  if (h['x-vercel-mitigated']) return 'vercel';
  if (server.includes('akamaighost') || /Access Denied[\s\S]{0,400}Reference #\d/i.test(body)) return 'akamai';
  if (h['x-amzn-waf-action'] || /Generated by cloudfront \(CloudFront\)/i.test(body)) return 'aws';
  return null;
}

/**
 * Kesin challenge isaretleri — durum kodu 200 olsa bile icerik yerine
 * dogrulama ekrani gelmistir. DIKKAT: Cloudflare "JavaScript detections"
 * NORMAL sayfalara da /cdn-cgi/challenge-platform/scripts/jsd/ betigi ekler;
 * Incapsula normal sayfalara /_Incapsula_Resource betigi ekler. Bunlar engel
 * DEGILDIR, o yuzden burada yoklar.
 */
const CHALLENGE_STRONG = /cf_chl_opt|\/cdn-cgi\/challenge-platform\/h\/[a-z]\/orchestrate|<title>\s*Just a moment\.\.\.\s*<\/title>/i;
/**
 * Bot koruma saticisinin YALNIZCA engel sayfasinda bulunan isaretleri
 * (DataDome captcha iframe'i, PerimeterX captcha'si). Normal bir sayfada
 * gecmezler; bu yuzden her hata durumunda (4xx/5xx) challenge sayilir.
 */
const VENDOR_CHALLENGE = /captcha-delivery\.com|px-captcha/i;
/**
 * Normal sayfalarda da bulunabilen genel dogrulama isaretleri: iletisim
 * formundaki reCAPTCHA/hCaptcha/Turnstile, Incapsula'nin her sayfaya ekledigi
 * betik. Yalnizca RED durumlarinda (401/403/429/503) sayilir — 404/410/500
 * sayilirsa formlu siradan bir 404 sayfasi "challenge" sanilir ve link
 * denetimi gercekten olu bir linke hukum veremez.
 */
const GENERIC_CHALLENGE = /_Incapsula_Resource|cf-turnstile|g-recaptcha|h-captcha/i;
const CHALLENGE_STATUSES = new Set([401, 403, 429, 503]);

/**
 * Guvenlik duvarinin KENDI urettigi red sayfasi (sitenin kendi 403'u degil).
 * Yalnizca 403/406 ile birlikte gecerli: "Cloudflare Ray ID" 520-526 kaynak
 * sunucu hatalarinda da gorunur ve onlar engel degil, sitenin kendi arizasidir.
 */
const WAF_BODY = /Attention Required! \| Cloudflare|Sorry, you have been blocked|cf-error-details|Cloudflare Ray ID|Sucuri WebSite Firewall - Access Denied|Incapsula incident ID|Request blocked\.[\s\S]{0,300}cloudfront|Access Denied[\s\S]{0,400}Reference #\d/i;

/**
 * Yaniti siniflandir. Engel yoksa null — 404/500/52x gibi durumlar ENGEL
 * DEGILDIR, onlar sitenin kendi durumudur ve cagiran taraf oyle raporlar.
 */
export function detectBlock(r: BlockProbe): BlockSignal | null {
  const h = r.headers ?? {};
  const body = (r.text ?? '').slice(0, 64 * 1024);
  const vendor = detectVendor(h, body);
  const who = vendor ? VENDOR_NAME[vendor] : null;
  const status = r.status;

  const mitigated = (h['cf-mitigated'] ?? h['x-vercel-mitigated'] ?? '').toLowerCase();
  const challenged = mitigated === 'challenge'
    || CHALLENGE_STRONG.test(body)
    || (status >= 400 && VENDOR_CHALLENGE.test(body))
    || (CHALLENGE_STATUSES.has(status) && GENERIC_CHALLENGE.test(body));
  if (challenged) {
    return {
      kind: 'challenge', vendor, status,
      reason: `${who ?? 'Site'} bot doğrulaması istedi; sayfa içeriği yerine doğrulama ekranı geldi (HTTP ${status}).`,
    };
  }

  if (status < 400) return null;

  if (status === 429) {
    return { kind: 'rate_limited', vendor, status, reason: 'Site çok fazla istek gerekçesiyle geçici olarak reddetti (HTTP 429).' };
  }
  if (status === 999 || ((status === 403 || status === 406) && WAF_BODY.test(body))) {
    return {
      kind: 'waf', vendor, status,
      reason: `${who ?? 'Sitenin'} güvenlik duvarı RanksUp tarayıcısını engelledi (HTTP ${status}).`,
    };
  }
  if (status === 401 || status === 407) {
    return { kind: 'auth', vendor, status, reason: `Sayfa giriş istiyor (HTTP ${status}).` };
  }
  if (status === 403 || status === 451) {
    return {
      kind: 'forbidden', vendor, status,
      reason: who ? `Site erişimi reddetti (HTTP ${status}, ${who} üzerinden).` : `Site erişimi reddetti (HTTP ${status}).`,
    };
  }
  if (status === 503) {
    return { kind: 'unavailable', vendor, status, reason: 'Site geçici olarak hizmet dışı (HTTP 503).' };
  }
  return null;
}

/**
 * Site sahibine ne yapmasi gerektigini soyleyen tek cumle. Engeli asmayi
 * degil, izin vermeyi anlatir.
 */
export function unblockHint(signal: BlockSignal): string {
  if (signal.kind === 'auth') return 'Herkese açık sayfalar giriş istememeli; arama motorları ve yapay zekâ tarayıcıları da bu sayfayı okuyamaz.';
  if (signal.kind === 'rate_limited' || signal.kind === 'unavailable') return 'Bir süre sonra tekrar deneyin; sürüyorsa sunucu kapasitesini ve hız sınırı kurallarını kontrol edin.';
  if (signal.vendor === 'cloudflare') {
    // Menu adlari ve Bot Fight Mode siniri Cloudflare dokumanindan (2026-10):
    // https://developers.cloudflare.com/waf/custom-rules/skip/
    // https://developers.cloudflare.com/bots/get-started/bot-fight-mode/
    return 'Cloudflare panelinde Security rules → Create rule → Custom rules ile, kullanıcı ajanı "RanksUpBot" içeren istekler için Skip eylemli bir kural ekleyin. Ücretsiz plandaki Bot Fight Mode bu kuralla atlanamıyor. Aynı ayarlar GPTBot, ClaudeBot, PerplexityBot gibi yapay zekâ tarayıcılarını da engelliyor olabilir. Ayrıntı: ranksup.ai/bot';
  }
  return 'Güvenlik duvarı / bot koruması ayarlarında "RanksUpBot" kullanıcı ajanına izin verin. Aynı kural yapay zekâ tarayıcılarını da engelliyor olabilir. Ayrıntı: ranksup.ai/bot';
}
